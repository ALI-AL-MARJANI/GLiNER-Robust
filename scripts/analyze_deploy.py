"""Summarize a deployment benchmark run: speed-ups, size ratios and F1 deltas vs PyTorch FP32.

Reads ``<run_dir>/results.json`` (from ``scripts/bench_deploy.py``) and writes
``<run_dir>/summary.json`` and ``<run_dir>/summary.md``. F1 deltas use a paired
bootstrap over test sentences (stratified by dataset for the average).

Usage:
    python -m scripts.analyze_deploy --run_dir results/deploy/apple-m4
"""

from __future__ import annotations

import json
import argparse
from typing import Any, Dict
from pathlib import Path

import numpy as np

from experiments.metrics import paired_bootstrap_average

REFERENCE = "pytorch_fp32"


def summarize(data: Dict[str, Any], n_resamples: int) -> Dict[str, Any]:
    backends = data["backends"]
    ref = backends[REFERENCE]
    datasets = list(ref["accuracy"])
    ref_counts = {n: [np.asarray(ref["accuracy"][n]["sentence_counts"])] for n in datasets}
    rows: Dict[str, Any] = {}
    for name, rec in backends.items():
        if "error" in rec:
            rows[name] = {"error": rec["error"].strip().splitlines()[-1]}
            continue
        row: Dict[str, Any] = {
            "size_mb": rec["size_mb"],
            "size_ratio_vs_reference": ref["size_mb"] / rec["size_mb"],
            "avg_f1": rec["accuracy_avg_f1"],
            "max_abs_dprob_vs_reference": rec["fidelity_vs_pytorch"]["max_abs_dprob"],
            "latency": {},
        }
        for key, lat in rec["latency"].items():
            row["latency"][key] = {
                "p50_ms": lat["p50_ms"],
                "p90_ms": lat["p90_ms"],
                "speedup_p50_vs_reference": ref["latency"][key]["p50_ms"] / lat["p50_ms"],
            }
        if name != REFERENCE:
            counts = {n: [np.asarray(rec["accuracy"][n]["sentence_counts"])] for n in datasets}
            row["delta_avg_f1_vs_reference"] = paired_bootstrap_average(ref_counts, counts, n_resamples=n_resamples)
        rows[name] = row
    return {"reference": REFERENCE, "datasets": datasets, "n_resamples": n_resamples, "backends": rows}


def _lat_cell(lat: Dict[str, float]) -> str:
    return f"{lat['p50_ms']:.1f} ({lat['speedup_p50_vs_reference']:.2f}x)"


def to_markdown(summary: Dict[str, Any], data: Dict[str, Any]) -> str:
    keys = list(next(r for r in summary["backends"].values() if "latency" in r)["latency"])
    head = ["backend", "size (MB)", "avg F1 (%)", "ΔF1 vs PyTorch [95% CI]", *[f"p50 {k} (ms)" for k in keys]]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for name, row in summary["backends"].items():
        if "error" in row:
            lines.append(f"| {name} | failed: {row['error']} |" + " |" * (len(head) - 2))
            continue
        d = row.get("delta_avg_f1_vs_reference")
        delta = f"{100 * d['delta_f1']:+.2f} [{100 * d['ci95_low']:+.2f}, {100 * d['ci95_high']:+.2f}]" if d else "—"
        lat = [_lat_cell(row["latency"][k]) for k in keys]
        cells = [name, f"{row['size_mb']:.0f}", f"{100 * row['avg_f1']:.2f}", delta, *lat]
        lines.append("| " + " | ".join(cells) + " |")
    env = data["env"]
    return "\n".join(
        [
            "<!-- generated by scripts/analyze_deploy.py; do not edit -->",
            f"{env['cpu']}, {data['config']['threads']} threads, {env['ram_gb']} GB RAM. "
            f"Latency keys: w<words>_b<batch>; (x) = PyTorch p50 / backend p50.",
            "",
            *lines,
        ]
    )


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--run_dir", default="results/deploy/apple-m4")
    p.add_argument("--n_resamples", type=int, default=10_000)
    a = p.parse_args()

    run_dir = Path(a.run_dir)
    data = json.loads((run_dir / "results.json").read_text())
    summary = summarize(data, a.n_resamples)
    (run_dir / "summary.json").write_text(json.dumps(summary, indent=1))
    md = to_markdown(summary, data)
    (run_dir / "summary.md").write_text(md + "\n")
    print(md)


if __name__ == "__main__":
    main()
